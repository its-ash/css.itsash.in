function cssImportUrl(fontNames) {
  const unique = [...new Set(fontNames)].filter(Boolean);
  if (!unique.length) return '';
  const famParam = unique.map(f => `family=${f.replace(/ /g, '+')}:wght@400;500;600;700`).join('&');
  return `https://fonts.googleapis.com/css2?${famParam}&display=swap`;
}

export function fontCssUrl(headingFont, bodyFont, monoFont) {
  return cssImportUrl([headingFont, bodyFont, monoFont]);
}

export function fontStack(name) {
  if (!name) return null;
  return `'${name}', ui-sans-serif, system-ui, sans-serif`;
}

export function monoStack(name) {
  if (!name) return null;
  return `'${name}', ui-monospace, monospace`;
}

export function autoPair(headingFont) {
  const entry = FONTS.find(f => f.name === headingFont);
  if (entry) {
    if (entry.pairWith) return entry.pairWith;
    if (entry.pairBy) return entry.pairBy;
  }
  return 'Inter';
}

export function autoMono(headingFont, bodyFont) {
  const tags = new Set([
    ...(FONTS.find(f => f.name === headingFont)?.tags ?? []),
    ...(FONTS.find(f => f.name === bodyFont)?.tags ?? []),
  ]);
  if (tags.has('tech') || tags.has('jetbrains')) return 'JetBrains Mono';
  if (tags.has('ibm')) return 'IBM Plex Mono';
  if (tags.has('google')) return 'Roboto Mono';
  if (tags.has('mozilla')) return 'Fira Mono';
  if (tags.has('space')) return 'Space Mono';
  return 'JetBrains Mono';
}